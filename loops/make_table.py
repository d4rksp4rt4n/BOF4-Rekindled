# loop_table.json -> reverb/loops_table.h (keyed by MP3 size + CRC32 of its first 4 KB, duplicates merged)
import json, os, zlib
import align

HERE = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(HERE, "loop_table.json")))
rows = {}
for key, v in sorted(t.items()):
    n, part = int(key[3:6]), int(key.split("/")[1])
    d, pcs = align.pc_parts(n); flag, tag, off, size = pcs[part]
    mp3 = d[off:off + size]
    k = (size, zlib.crc32(mp3[:4096]))
    if k in rows and (rows[k][0], rows[k][1]) != (v["E"], v["P"]):
        print("note: same recording, different loop", key, rows[k][2])
    rows.setdefault(k, (v["E"], v["P"], key))
bv = os.path.join(HERE, "boss_victory.json")         # option "bossvic": the rendered boss victory themes
if os.path.exists(bv):
    for key, v in sorted(json.load(open(bv)).items()):
        rows[(v["size"], v["crc"])] = (v["E"], v["P"], key + " boss victory (rendered)")
with open(os.path.join(HERE, "..", "reverb", "loops_table.h"), "w") as f:
    f.write("/* generated by loops/make_table.py: size, crc32(first 4 KB), E, P (samples) */\n")
    f.write("static const Loop LOOPS[] = {\n")
    for (size, crc), (E, P, key) in sorted(rows.items(), key=lambda r: r[1][2]):
        f.write(f"    {{{size}, 0x{crc:08X}u, {E}, {P}}},   /* {key} */\n")
    f.write("};\n")
print(len(t), "loops ->", len(rows), "distinct recordings")
